"""Generate hdl/hog_tables.v (ROMs, weights, constants) from hog_fixed.py.

    python gen_tables.py
"""
import os
import hog_fixed as hf

SUB, TPS = 6, 6                      # sublanes per lane, features per sublane
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'hdl', 'hog_tables.v')


def rom(name, width, abits, values):
    """ROM as an array filled at time 0: synthesises to a ROM, simulates fast."""
    n = len(values)
    lines = [f'module {name} (input wire clk, input wire [{abits-1}:0] a, output reg [{width-1}:0] q);',
             f'    reg [{width-1}:0] mem [0:{n-1}];',
             '    initial begin']
    for i, v in enumerate(values):
        lines.append(f"        mem[{i}] = {width}'d{int(v)};")
    lines += ['    end',
              f'    always @(posedge clk) q <= mem[a];',
              'endmodule', '']
    return '\n'.join(lines)


def main():
    wq, rho = hf.weights()
    out = ['// Generated by model/gen_tables.py from model/hog_fixed.py. Do not edit.',
           '`timescale 1ns / 1ps', '']
    out.append(rom('hog_gamma_rom', 8, 8, hf.GAMMA_LUT))
    out.append(rom('hog_sqrt_rom', 13, 12, hf.SQRT_LUT))
    out.append(rom('hog_recip_rom', 13, 11, hf.RECIP_LUT))

    # weight ROM: lane j, sublane s, address i*TPS + t holds W[i][j][s*TPS + t].
    # The case runs once per entry at time 0 to fill each instance's 42 words.
    lines = ['module hog_wrom #(parameter integer LANE = 0, parameter integer SUB = 0) (',
             '    input wire clk, input wire [5:0] a, output reg signed [15:0] q);',
             '    reg signed [15:0] mem [0:41];',
             '    integer k;',
             '    function signed [15:0] w(input integer key);',
             '        case (key)']
    for j in range(15):
        for s in range(SUB):
            for i in range(7):
                for t in range(TPS):
                    v = int(wq[i, j, s * TPS + t])
                    key = (j << 9) | (s << 6) | (i * TPS + t)
                    lit = f"-16'sd{-v}" if v < 0 else f"16'sd{v}"
                    lines.append(f"            {key}: w = {lit};")
    lines += ["            default: w = 16'sd0;", '        endcase', '    endfunction',
              '    initial for (k = 0; k < 42; k = k + 1) mem[k] = w(LANE * 512 + SUB * 64 + k);',
              '    always @(posedge clk) q <= mem[a];',
              'endmodule', '']
    out.append('\n'.join(lines))

    atan = ', '.join(str(a) for a in hf.ATAN)
    with open(OUT, 'w') as f:
        f.write('\n'.join(out))

    with open(os.path.join(HERE, '..', 'hdl', 'hog_params.vh'), 'w') as f:
        f.write('// Generated by model/gen_tables.py. Do not edit.\n')
        for i, a in enumerate(hf.ATAN):
            f.write(f'localparam integer ATAN{i} = {a};\n')
        f.write(f'localparam integer EPS1 = {hf.EPS1};\n')
        f.write(f'localparam integer EPS2 = {hf.EPS2};\n')
        f.write(f'localparam integer CLIP = {hf.CLIP};\n')
        f.write(f'localparam signed [39:0] RHO = {rho};\n')
    print('wrote', os.path.normpath(OUT), 'rho', rho, 'atan', atan)


if __name__ == '__main__':
    main()
